def _embed_images(store: RunStore, md_text: str) -> str:
    def repl(m: re.Match[str]) -> str:
        alt, src = m.group(1), m.group(2).strip()
        if src.startswith(("http", "data:")):
            return m.group(0)
        for candidate in (src, src.lstrip("./"), f"eda/charts/{src.split('/')[-1]}", f"evaluation/{src.split('/')[-1]}",
                          f"report/{src.split('/')[-1]}"):
            if store.exists(candidate) and candidate.endswith(".png"):
                data = base64.b64encode(store.resolve(candidate).read_bytes()).decode()
                return f"![{alt}](data:image/png;base64,{data})"
        return f"*(missing image: {html.escape(src)})*"
    return re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", repl, md_text)


def _fmt(v: Any) -> str:
    return f"{v:.4g}" if isinstance(v, float) else str(v)


def facts_appendix(store: RunStore, state: dict[str, Any], budget: dict[str, Any]) -> str:
    spec = state.get("objective_spec") or {}
    final = state.get("final") or {}
    lines = ["## Appendix — recorded facts (generated by the orchestrator)", ""]
    metric = spec.get("primary_metric")
    if final.get("holdout"):
        h = final["holdout"]
        lines += [f"**Locked holdout evaluation** (n = {h['n_holdout']}, evaluated once):", "",
                  "| metric | model | naive baseline |", "|---|---|---|"]
        for k, v in h["metrics"].items():
            lines.append(f"| {'**' + k + '**' if k == metric else k} | {_fmt(v)} | {_fmt(h['baseline'].get(k, ''))} |")
        lines.append("")
        lines.append(f"Success threshold for {metric}: {spec.get('success_threshold')} → "
                     f"{'met' if final.get('threshold_met') else 'not met'}.")
    elif final.get("holdout_error"):
        lines.append(f"Holdout evaluation not available: {final['holdout_error']}")
    sources = store.read_json("raw/sources.json", default=[]) or []
    if sources:
        lines += ["", "### Data sources and licenses", "", "| file | source | license | retrieved | sha256 |", "|---|---|---|---|---|"]
        for s in sources:
            url = s.get("url", "")
            lines.append(f"| `{s.get('path')}` | [{s.get('source_name') or url}]({url}) | {s.get('license')} | "
                         f"{s.get('retrieved_at', '')} | `{str(s.get('sha256', ''))[:12]}` |")
    hist = state.get("phase_history") or []
    if hist:
        lines += ["", "### Process trace (gates and routing)", "", "| # | phase | gate | critic | next | reason |", "|---|---|---|---|---|---|"]
        for i, h in enumerate(hist, 1):
            lines.append(f"| {i} | {LABELS.get(h['node'], h['node'])} | {h.get('decision')} | {_fmt(h.get('critic_score', ''))} | "
                         f"{LABELS.get(h.get('next', ''), h.get('next', ''))} | {str(h.get('rationale', ''))[:160]} |")
    lines += ["", "### Budget", "",
              f"LLM spend ${budget.get('usd', 0):.3f} of ${budget.get('limits', {}).get('max_usd', 0):.2f}; "
              f"{budget.get('total_tokens', 0):,} tokens in {budget.get('llm_calls', 0)} calls; "
              f"{budget.get('elapsed_seconds', 0) / 60:.1f} min active time."]
    if state.get("stop_reason"):
        lines += ["", f"**Run stopped early:** {state['stop_reason']}"]
    return "\n".join(lines)


def render(store: RunStore, state: dict[str, Any], budget: dict[str, Any], body_md: str) -> str:
    spec = state.get("objective_spec") or {}
    title = spec.get("title") or state.get("objective", "Analytics report")
    full_md = _embed_images(store, body_md) + "\n\n<div class='appendix'>\n\n" + facts_appendix(store, state, budget) + "\n\n</div>"
    body = markdown.markdown(full_md, extensions=["tables", "fenced_code", "sane_lists", "md_in_html"])
    doc = (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' "
           f"content='width=device-width,initial-scale=1'><title>{html.escape(title)}</title><style>{CSS}</style></head>"
           f"<body><main><p class='meta'>Run {html.escape(store.run_id)} · generated {time.strftime('%Y-%m-%d %H:%M')}</p>"
           f"{body}</main></body></html>")
    store.write_text("report/final_report.html", doc)
    return "report/final_report.html"


def fallback_markdown(store: RunStore, state: dict[str, Any]) -> str:
    """Used when no LLM budget is left: an honest, template-based report."""
    spec = state.get("objective_spec") or {}
    outs = state.get("phase_outputs") or {}
    parts = [f"# {spec.get('title') or state.get('objective')}", "",
             f"**Objective:** {state.get('objective')}  ", f"**Region:** {state.get('region') or 'n/a'}", ""]
    if state.get("stop_reason"):
        parts += [f"> This run ended early: {state['stop_reason']}. The report below summarises the best result so far.", ""]
    for node in ("define_data", "collect_data", "prepare_store", "eda", "modeling", "evaluation"):
        if node in outs:
            parts += [f"## {LABELS[node]}", "", "```json", json.dumps(outs[node], indent=1, default=str)[:2500], "```", ""]
    for rel in ("data_card.md", "eda/eda_report.md"):
        if store.exists(rel):
            parts += [f"## {rel}", "", store.read_text(rel, 6000), ""]
    return "\n".join(parts)
